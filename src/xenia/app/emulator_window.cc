          ImVec2 cancel_text_pos(
              cancel_button_min.x +
                  (cancel_button_max.x - cancel_button_min.x -
                   cancel_text_size.x) *
                      0.5f,
              cancel_button_min.y +
                  (cancel_button_max.y - cancel_button_min.y -
                   cancel_text_size.y) *
                      0.5f);
